function dY = TremasseFun(~,Y)

global m1 m2 m3

dY = zeros(12,1);

dY(1:2)  = Y(3:4);
dY(5:6)  = Y(7:8);
dY(9:10) = Y(11:12);

r12 = Y(1:2)  - Y(5:6);    r21 = -r12;   d12 = norm(r12);   d21 = d12;
r23 = Y(5:6)  - Y(9:10);   r32 = -r23;   d23 = norm(r23);   d32 = d23;
r31 = Y(9:10) - Y(1:2);    r13 = -r31;   d31 = norm(r31);   d13 = d31;

dY(3:4)   = m2*(r21/(d21^3)) + m3*(r31/(d31^3));
dY(7:8)   = m3*(r32/(d32^3)) + m1*(r12/(d12^3));
dY(11:12) = m1*(r13/(d13^3)) + m2*(r23/(d23^3));

end

